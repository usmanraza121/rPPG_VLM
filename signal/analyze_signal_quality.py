#!/usr/bin/env python3
"""Analyze saved waveform quality metrics for SSMamba outputs.

This script expects the artifact generated by SSMambaTrainer.save_signal_quality_outputs:
  LOG.PATH/signal_quality/waveforms.pt

It computes per-subject metrics between prediction and GT:
- Pearson correlation
- DTW distance (and normalized DTW)
- SNR in dB (projection-based)
- PSD correlation

Usage:
  python signal/analyze_signal_quality.py \
      --input runs/exp/<exp_name>/signal_quality/waveforms.pt \
      --pred-key pred_norm \
      --output signal/signal_quality_report.csv
"""

import argparse
import csv
import json
import math
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
import torch

try:
    from scipy.signal import welch
except Exception:  # pragma: no cover
    welch = None


def to_1d_numpy(x: torch.Tensor) -> np.ndarray:
    arr = x.detach().cpu().numpy().astype(np.float64)
    return arr.reshape(-1)


def reconstruct_subject_signal(subject_chunks: Dict[int, torch.Tensor]) -> np.ndarray:
    ordered_keys = sorted(subject_chunks.keys())
    chunks = [to_1d_numpy(subject_chunks[k]) for k in ordered_keys]
    if not chunks:
        return np.array([], dtype=np.float64)
    return np.concatenate(chunks, axis=0)


def pearson_corr(x: np.ndarray, y: np.ndarray) -> float:
    x = x.reshape(-1)
    y = y.reshape(-1)
    n = min(len(x), len(y))
    if n == 0:
        return float("nan")
    x = x[:n]
    y = y[:n]
    x_std = np.std(x)
    y_std = np.std(y)
    if x_std < 1e-12 or y_std < 1e-12:
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


def dtw_distance(x: np.ndarray, y: np.ndarray) -> float:
    """Classic O(n*m) DTW using absolute difference cost."""
    n = len(x)
    m = len(y)
    if n == 0 or m == 0:
        return float("nan")

    dp = np.full((n + 1, m + 1), np.inf, dtype=np.float64)
    dp[0, 0] = 0.0

    for i in range(1, n + 1):
        xi = x[i - 1]
        for j in range(1, m + 1):
            cost = abs(xi - y[j - 1])
            dp[i, j] = cost + min(dp[i - 1, j], dp[i, j - 1], dp[i - 1, j - 1])

    return float(dp[n, m])


def projection_snr_db(pred: np.ndarray, gt: np.ndarray) -> float:
    """Compute SNR by projecting pred onto gt as signal component.

    signal = a * gt, where a = <pred, gt> / <gt, gt>
    noise = pred - signal
    """
    n = min(len(pred), len(gt))
    if n == 0:
        return float("nan")

    p = pred[:n]
    g = gt[:n]

    denom = float(np.dot(g, g))
    if denom < 1e-12:
        return float("nan")

    a = float(np.dot(p, g) / denom)
    signal = a * g
    noise = p - signal

    p_sig = float(np.mean(signal ** 2))
    p_noise = float(np.mean(noise ** 2))

    if p_noise < 1e-12:
        return float("inf")
    if p_sig < 1e-12:
        return float("-inf")

    return float(10.0 * math.log10(p_sig / p_noise))


def compute_psd(x: np.ndarray, fs: float) -> Tuple[np.ndarray, np.ndarray]:
    n = len(x)
    if n == 0:
        return np.array([]), np.array([])

    if welch is not None:
        f, pxx = welch(x, fs=fs, nperseg=min(256, n))
        return f, pxx

    # Fallback to simple periodogram using rFFT.
    x = x - np.mean(x)
    fft = np.fft.rfft(x)
    pxx = (np.abs(fft) ** 2) / max(n, 1)
    f = np.fft.rfftfreq(n, d=1.0 / fs)
    return f, pxx


def psd_correlation(pred: np.ndarray, gt: np.ndarray, fs: float, fmin: float = 0.7, fmax: float = 4.0) -> float:
    fp, pp = compute_psd(pred, fs)
    fg, pg = compute_psd(gt, fs)
    if len(fp) == 0 or len(fg) == 0:
        return float("nan")

    f_common = fp if len(fp) <= len(fg) else fg
    if len(f_common) == 0:
        return float("nan")

    pp_i = np.interp(f_common, fp, pp)
    pg_i = np.interp(f_common, fg, pg)

    band = (f_common >= fmin) & (f_common <= fmax)
    if not np.any(band):
        return float("nan")

    xp = np.log(pp_i[band] + 1e-12)
    xg = np.log(pg_i[band] + 1e-12)
    if np.std(xp) < 1e-12 or np.std(xg) < 1e-12:
        return float("nan")

    return float(np.corrcoef(xp, xg)[0, 1])


def as_float_safe(value: float) -> float:
    if value is None:
        return float("nan")
    return float(value)


def summarize(metrics_rows: List[Dict[str, float]]) -> Dict[str, float]:
    if not metrics_rows:
        return {}

    keys = [
        "pearson",
        "dtw",
        "dtw_norm",
        "snr_db",
        "psd_corr",
    ]

    summary = {}
    for k in keys:
        vals = [row[k] for row in metrics_rows if np.isfinite(row[k])]
        if vals:
            summary[f"{k}_mean"] = float(np.mean(vals))
            summary[f"{k}_std"] = float(np.std(vals))
            summary[f"{k}_median"] = float(np.median(vals))
        else:
            summary[f"{k}_mean"] = float("nan")
            summary[f"{k}_std"] = float("nan")
            summary[f"{k}_median"] = float("nan")
    return summary


def find_default_waveform_path() -> Path:
    """Find the newest waveforms.pt under runs/**/signal_quality/."""
    repo_root = Path(__file__).resolve().parents[1]
    candidates = list(repo_root.glob("runs/**/signal_quality/waveforms.pt"))
    if not candidates:
        return Path()
    return max(candidates, key=lambda p: p.stat().st_mtime)


def main() -> None:
    parser = argparse.ArgumentParser(description="Signal quality analysis for SSMamba waveforms")
    parser.add_argument(
        "--input",
        default=None,
        help="Path to waveforms.pt (auto-detects newest file under runs/**/signal_quality if omitted)",
    )
    parser.add_argument("--pred-key",
                        default="pred_norm",
                        choices=["pred_norm", "pred_raw"],
                        help="Prediction variant to compare with GT",
    )
    parser.add_argument(
        "--dtw-step",
        type=int,
        default=1,
        help="Downsample step for DTW speed-up (>=1), e.g. 2 or 4 for long signals",
    )
    parser.add_argument(
        "--output",
        default="signal/signal_quality_report.csv",
        help="CSV output path for per-subject metrics",
    )
    parser.add_argument(
        "--summary-json",
        default="signal/signal_quality_summary.json",
        help="JSON output path for aggregate summary",
    )
    args, unknown = parser.parse_known_args()
    if unknown:
        print("Ignoring unknown args:", unknown)

    in_path = Path(args.input) if args.input else find_default_waveform_path()
    if not str(in_path):
        raise FileNotFoundError(
            "No waveforms.pt found automatically. Please pass --input /path/to/waveforms.pt"
        )
    if not in_path.exists():
        raise FileNotFoundError(f"Input file not found: {in_path}")

    blob = torch.load(in_path, map_location="cpu")
    pred_dict = blob[args.pred_key]
    gt_dict = blob["gt"]
    fs = float(blob.get("fs", 30.0))

    rows: List[Dict[str, float]] = []

    common_subjects = sorted(set(pred_dict.keys()) & set(gt_dict.keys()))
    for subj in common_subjects:
        pred_signal = reconstruct_subject_signal(pred_dict[subj])
        gt_signal = reconstruct_subject_signal(gt_dict[subj])

        n = min(len(pred_signal), len(gt_signal))
        if n == 0:
            continue

        pred_signal = pred_signal[:n]
        gt_signal = gt_signal[:n]

        pear = as_float_safe(pearson_corr(pred_signal, gt_signal))

        step = max(int(args.dtw_step), 1)
        pred_dtw = pred_signal[::step]
        gt_dtw = gt_signal[::step]
        dtw = as_float_safe(dtw_distance(pred_dtw, gt_dtw))
        dtw_norm = as_float_safe(dtw / max(len(pred_dtw), len(gt_dtw), 1)) if np.isfinite(dtw) else float("nan")

        snr = as_float_safe(projection_snr_db(pred_signal, gt_signal))
        pcor = as_float_safe(psd_correlation(pred_signal, gt_signal, fs=fs))

        rows.append(
            {
                "subject": str(subj),
                "num_samples": int(n),
                "pearson": pear,
                "dtw": dtw,
                "dtw_norm": dtw_norm,
                "snr_db": snr,
                "psd_corr": pcor,
            }
        )

    out_csv = Path(args.output)
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    with out_csv.open("w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["subject", "num_samples", "pearson", "dtw", "dtw_norm", "snr_db", "psd_corr"],
        )
        writer.writeheader()
        writer.writerows(rows)

    summary = summarize(rows)
    summary["num_subjects"] = len(rows)
    summary["pred_key"] = args.pred_key
    summary["dtw_step"] = max(int(args.dtw_step), 1)
    summary["fs"] = fs

    out_json = Path(args.summary_json)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(summary, indent=2))

    print("Saved per-subject metrics:", out_csv)
    print("Saved summary:", out_json)
    print("Subjects analyzed:", len(rows))


if __name__ == "__main__":
    main()
